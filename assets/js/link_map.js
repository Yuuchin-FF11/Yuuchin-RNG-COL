// 英語のキーワードリスト
export const keywordsEn = ['Main Weapon', 'Sub', 'Ranged Weapon', 'Ammo', 'Head', 'Body', 'Hands', 'Legs', 'Feet', 'Neck', 'Left Ear', 'Right Ear', 'Left Ring', 'Right Ring', 'Back', 'Waist'];

// 装備品の正規化関数
export function normalizeEquipmentName(searchName, isEn) {
    let normalizedName = searchName;

    // 1. 略称変換
    const activeAbbrMap = isEn ? {
        'LA': 'Lanun', 'CS': 'Chasseur\'s', 'LK': 'Laksamana\'s', 'LU': 'Luzaf', 'HV': 'Herberton', 'AM': 'Amini', 'OR': 'Orion', 'AR': 'Arcadian'
    } : {
        'ＬＡ': 'ラヌン', 'LA': 'ラヌン',
        'ＣＳ': 'シャスー', 'CS': 'シャスー',
        'ＬＫ': 'ラクサマナ', 'LK': 'ラクサマナ',
        'ＬＵ': 'ルザフ', 'LU': 'ルザフ',
        'ＨＶ': 'ハーバートン', 'HV': 'ハーバートン',
        'ＡＭ': 'アミニ', 'AM': 'アミニ',
        'ＯＲ': 'オリオン', 'OR': 'オリオン',
        'ＡＲ': 'アルケ', 'AR': 'アルケ'
    };

    for (let key in activeAbbrMap) {
        if (normalizedName.startsWith(key)) {
            normalizedName = normalizedName.replace(key, activeAbbrMap[key]);
            break;
        }
    }

    // 2. ランク文字の削除
    normalizedName = normalizedName.replace(/[Ａ-ＺA-Z]$/, '').trim();

    // 3. 例外名・個別部位名から全体一覧/特定リンクへの置き換えルール
    if (isEn) {
        if (normalizedName.startsWith('Nyame')) normalizedName = 'Nyame';
        else if (normalizedName.startsWith('Ikenga')) normalizedName = 'Ikenga';
        else if (normalizedName.startsWith('Malignance')) normalizedName = 'Malignance';
        else if (normalizedName.startsWith('Lanun')) normalizedName = 'Lanun';
        else if (normalizedName.startsWith('Chasseur\'s') && !normalizedName.includes('Earring')) normalizedName = 'Chasseur\'s';
        else if (normalizedName.startsWith('Laksamana\'s')) normalizedName = 'Laksamana\'s';
        else if (normalizedName.startsWith('Rostam')) normalizedName = 'Rostam';
        else if (normalizedName.startsWith('Adhemar')) normalizedName = 'Adhemar Jacket';
        else if (normalizedName.startsWith('Herculean')) normalizedName = 'Herculean';
        else if (normalizedName.startsWith('Arvina Ring')) normalizedName = 'Arvina Ring';
        else if (normalizedName.startsWith('Hauksbok Bullet')) normalizedName = 'Hauksbok Bullet';
        else if (normalizedName.startsWith('Mummu')) {
            if (normalizedName.includes('Mask')) normalizedName = 'Mummu Mask';
            else if (normalizedName.includes('Gorget')) normalizedName = 'Mummu Gorget';
            else if (normalizedName.includes('Cape')) normalizedName = 'Mummu Cape';
            else if (normalizedName.includes('Sash')) normalizedName = 'Mummu Sash';
        }
        else if (normalizedName.startsWith('Carmine Finger')) normalizedName = 'Carmine Finger';
        else if (normalizedName.startsWith('Amini') && !['Amini Caban', 'Amini Gapette', 'Amini Brague', 'Amini Bottillon', 'Amini Bottillons'].includes(normalizedName)) normalizedName = 'Amini Attire';
        else if (normalizedName.startsWith('Orion') && !['Orion Braccae', 'Orion Beret', 'Orion Jerkin', 'Orion Gloves', 'Orion Socks'].includes(normalizedName)) normalizedName = 'Orion Attire';
        else if (normalizedName.startsWith('Arcadian') && !['Arcadian Beret', 'Arcadian Jerkin', 'Arcadian Bracers', 'Arcadian Braccae', 'Arcadian Socks'].includes(normalizedName)) normalizedName = 'Arcadian Attire';
    } else {
        if (normalizedName.startsWith('ニャメ')) normalizedName = 'ニャメ装束';
        else if (normalizedName.startsWith('イケンガ')) normalizedName = 'イケンガ装束';
        else if (normalizedName.startsWith('マリグナス') && !normalizedName.includes('ピアス')) normalizedName = 'マリグナス装束';
        else if (normalizedName.startsWith('ラヌン') && !normalizedName.includes('ナイフ')) normalizedName = 'ラヌンアタイア';
        else if (normalizedName.startsWith('シャスー') && !normalizedName.includes('ピアス')) normalizedName = 'シャスーアタイア';
        else if (normalizedName.startsWith('ラクサマナ')) normalizedName = 'ラクサマナアタイア';
        else if (normalizedName.startsWith('ロスタム')) normalizedName = 'ロスタム';
        else if (normalizedName.startsWith('アデマ')) normalizedName = 'アデマ装束';
        else if (normalizedName.startsWith('テーオン')) normalizedName = 'テーオン装束';
        else if (normalizedName.startsWith('ヘルクリア')) normalizedName = 'ヘルクリア装束';
        else if (normalizedName.startsWith('オショシ')) normalizedName = 'オショシ装束';
        else if (normalizedName.startsWith('ハーバートン')) normalizedName = 'ハーバートンリング';
        else if (normalizedName.startsWith('ルザフ')) normalizedName = 'ルザフリング';
        else if (normalizedName.startsWith('アミニ') && !['アミニカバン', 'アミニガペット', 'アミニブラーグ', 'アミニボティヨン'].includes(normalizedName)) normalizedName = 'アミニアタイア';
        else if (normalizedName.startsWith('オリオン') && !['オリオンブラッカエ', 'オリオンベレー', 'オリオンジャーキン', 'オリオングローブ', 'オリオンソックス'].includes(normalizedName)) normalizedName = 'オリオンアタイア';
        else if (normalizedName.startsWith('ベレナ')) normalizedName = 'ベレナスケープ';
        else if (normalizedName.startsWith('スカウト')) normalizedName = 'スカウトゴルゲット';
        else if (normalizedName.startsWith('アルケ') && !['アルケベレー', 'アルケジャーキン', 'アルケブレーサー', 'アルケブラッカエ', 'アルケソックス'].includes(normalizedName)) normalizedName = 'アルケアタイア';
        else if (normalizedName.startsWith('アルカディア') && !['アルカディアベレー', 'アルカディアジャーキン', 'アルカディアグローブ', 'アルカディアブラッカエ', 'アルカディアソックス'].includes(normalizedName)) normalizedName = 'アルカディアアタイア';
    }

    return normalizedName;
}
